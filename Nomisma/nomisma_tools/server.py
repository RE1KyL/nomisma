"""Nomisma stdio MCP service. Stdout is exclusively managed by the SDK."""

from datetime import datetime, timezone
import json
import logging
import os
from pathlib import Path
import sys
import uuid

import anyio
from mcp.server import Server
from mcp.server.stdio import stdio_server
from mcp import types

from data_tools import TOOL_VERSION, nomisma_health_check
from dataset_store import ProjectDatasetStore, DatasetError
from mcp_contract import SPECS, OUTPUT_SCHEMA, visible, validate, bounded, error_result
from mcp_jobs import run_job

INPUT_SCHEMA = {"type": "object", "properties": {}, "additionalProperties": False}
LOG = logging.getLogger("nomisma.audit")


def record(event: str, **fields) -> None:
    LOG.info(json.dumps({"time": datetime.now(timezone.utc).isoformat(),
                         "event": event, "pid": os.getpid(), **fields}, ensure_ascii=False))


def current_mode():
    # A missing or invalid binding never exposes research tools.
    try:return ProjectDatasetStore().context['mode']
    except DatasetError:return None


async def list_tools(ctx, params):
    mode=current_mode()
    tools=visible(mode) if mode else {'nomisma_health_check':SPECS['nomisma_health_check']}
    return types.ListToolsResult(tools=[types.Tool(name=name,
        description=spec['description'],inputSchema=spec['inputSchema'],outputSchema=OUTPUT_SCHEMA,
        annotations=types.ToolAnnotations(readOnlyHint=spec['read_only'],destructiveHint=False,
                                         idempotentHint=False,openWorldHint=name in ('nomisma_akshare_fetch','nomisma_macro_fetch','nomisma_explore_fetch')))
        for name,spec in tools.items()])


async def call_tool(ctx, params):
    execution_id=uuid.uuid4().hex
    name=params.name;arguments=params.arguments or {}
    record('tool_requested',request_id=execution_id,tool=name if name in SPECS else 'unregistered')
    try:
        if name=='nomisma_health_check':
            validate(name,arguments,None)
            with anyio.fail_after(3):
                result=await anyio.to_thread.run_sync(nomisma_health_check,abandon_on_cancel=True)
            # Preserve health receipt identity generated by its original API.
            execution_id=result['data']['execution_id']
            record('tool_started',execution_id=execution_id,tool=name)
        else:
            store=ProjectDatasetStore();validate(name,arguments,store.context['mode'])
            record('tool_started',execution_id=execution_id,tool=name,
                   project_id=store.context['project_id'],mode=store.context['mode'])
            result=await run_job(store,name,arguments,execution_id,record)
        bounded(result)
    except anyio.get_cancelled_exc_class():
        record('tool_cancelled',execution_id=execution_id,tool=name if name in SPECS else 'unregistered');raise
    except DatasetError as error:
        result=error_result(error.code,execution_id)
    except TimeoutError:result=error_result('TIMEOUT',execution_id,'tool_error')
    except PermissionError:result=error_result('PERMISSION_DENIED',execution_id,'file_permission_error')
    except Exception:result=error_result('TOOL_EXECUTION_FAILED',execution_id,'tool_error')
    if not result['ok'] and isinstance(arguments.get('request_id'),str):
        import re
        if re.fullmatch(r'[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}',arguments['request_id']):
            result['data']['request_id']=arguments['request_id']
    record('tool_finished',execution_id=result['data'].get('execution_id',execution_id),tool=name if name in SPECS else 'unregistered',
           ok=result['ok'],error_code=result['error']['code'] if result['error'] else None,
           analysis_id=result['data'].get('analysis_id'),dataset_id=result['data'].get('dataset_id'))
    raw=json.dumps(result,ensure_ascii=False,allow_nan=False,sort_keys=True,separators=(',',':'))
    return types.CallToolResult(content=[types.TextContent(type='text',text=raw)],structuredContent=result,isError=not result['ok'])


async def main():
    log_dir = Path(os.environ.get("NOMISMA_LOG_DIR", str(
        Path(os.environ["LOCALAPPDATA"]) / "Nomisma/logs/python")))
    if not log_dir.is_absolute():
        raise ValueError("NOMISMA_LOG_DIR must be absolute")
    log_dir.mkdir(parents=True, exist_ok=True)
    stream = (log_dir / f"mcp-{os.getpid()}-{uuid.uuid4().hex}.jsonl").open("x", encoding="utf8")
    handler = logging.StreamHandler(stream)
    LOG.addHandler(handler)
    LOG.setLevel(logging.INFO)
    LOG.propagate = False
    server = Server("nomisma-tools", version=TOOL_VERSION, on_list_tools=list_tools,
                    on_call_tool=call_tool,
                    get_tool_input_schema=lambda name: SPECS[name]['inputSchema'] if name in (
                        visible(current_mode()) if current_mode() else {'nomisma_health_check'}) else None)
    record("service_started", python_version=sys.version.split()[0])
    try:
        async with stdio_server() as (read, write):
            await server.run(read, write, server.create_initialization_options())
    finally:
        record("service_stopped")
        LOG.removeHandler(handler)
        stream.close()


if __name__ == "__main__":
    anyio.run(main)
